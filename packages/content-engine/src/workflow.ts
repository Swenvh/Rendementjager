export type WorkflowErrorCode =
  | 'NOT_FOUND'
  | 'INVALID_INPUT'
  | 'INVALID_ACTOR'
  | 'INVALID_TRANSITION'
  | 'GATE_NOT_SATISFIED'
  | 'EMERGENCY_STOP'
  | 'NOT_AUTHORIZED'
  | 'BINDING_MISMATCH'
  | 'SELF_REVIEW'
  | 'DUPLICATE_TOPIC'
  | 'ALREADY_PUBLISHED';

export class WorkflowError extends Error {
  constructor(
    readonly code: WorkflowErrorCode,
    message: string,
    readonly details: Record<string, unknown> = {},
  ) {
    super(message);
    this.name = 'WorkflowError';
  }
}

/** Actors allowed to move an item to SCHEDULED / PUBLISHED (G5 by the owner is still required). */
export const PUBLISHING_ACTORS: readonly ActorId[] = ['owner', 'distribution-manager', 'automation-engineer', 'chief-of-staff'];

/** Stages from which a changed asset/caption demotes the item (G5 no longer valid). */
const POST_RENDER_STAGES: readonly PipelineStage[] = ['RENDERED', 'QA_REVIEW', 'READY_FOR_EDITOR', 'APPROVED_FOR_PUBLISHING', 'SCHEDULED'];

/** Prefix of the notes of an owner-recorded G1 that points at an approved method brief (brief id + hash). */
export const METHOD_G1_MARKER = 'METHOD_BRIEF_G1 ';

export interface MethodG1Reference {
  v: 1;
  briefId: string;
  briefHash: string;
  kind: MethodKind;
}

export function parseMethodG1(notes: string | null | undefined): MethodG1Reference | null {
  if (!notes?.startsWith(METHOD_G1_MARKER)) return null;
  try {
    const r = JSON.parse(notes.slice(METHOD_G1_MARKER.length)) as Partial<MethodG1Reference>;
    if (r.v === 1 && typeof r.briefId === 'string' && typeof r.briefHash === 'string' && (METHOD_KINDS as readonly string[]).includes(r.kind as string)) return r as MethodG1Reference;
  } catch {
    /* fall through */
  }
  return null;
}

/** Series kind of an item generated by @rj/series-engine (notes JSON `{rj:"series/1", tags:{kind}}`), else null. */
export function seriesKindOf(item: Pick<ContentIdea, 'notes'>): MethodKind | null {
  if (!item.notes?.startsWith('{')) return null;
  try {
    const n = JSON.parse(item.notes) as { rj?: string; tags?: { kind?: string } };
    const k = n.rj === 'series/1' ? n.tags?.kind : undefined;
    return (METHOD_KINDS as readonly string[]).includes(k as string) ? (k as MethodKind) : null;
  } catch {
    return null;
  }
}

